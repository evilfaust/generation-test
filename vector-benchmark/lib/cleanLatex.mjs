// Лёгкая чистка LaTeX → читаемый текст перед эмбеддингом.
// Цель: убрать разметку, которая мешает текстовой модели, сохранив смысл.
// НЕ полноценный парсер — намеренно простой, для бенчмарка достаточно.

export function cleanLatex(input) {
  if (!input) return '';
  let s = String(input);

  // 1. Снять обёртки формул: $...$, $$...$$, \( \), \[ \]
  s = s.replace(/\$\$?/g, ' ');
  s = s.replace(/\\[()[\]]/g, ' ');

  // 2. Дроби \frac{a}{b} и \dfrac → (a)/(b). Несколько проходов для вложенности.
  for (let i = 0; i < 3; i++) {
    s = s.replace(/\\d?frac\s*\{([^{}]*)\}\s*\{([^{}]*)\}/g, '($1)/($2)');
  }

  // 3. Корни \sqrt{x} → sqrt(x), \sqrt[n]{x} → корень n-й степени из (x)
  s = s.replace(/\\sqrt\s*\[([^\]]*)\]\s*\{([^{}]*)\}/g, 'корень $1-й степени из ($2)');
  s = s.replace(/\\sqrt\s*\{([^{}]*)\}/g, 'sqrt($1)');

  // 4. Степени и индексы: x^{2} → x^2, a_{n} → a_n (убрать фигурные скобки)
  s = s.replace(/\^\s*\{([^{}]*)\}/g, '^$1');
  s = s.replace(/_\s*\{([^{}]*)\}/g, '_$1');

  // 5. Частые команды → слова/символы
  const cmd = {
    '\\cdot': '*', '\\times': '*', '\\div': '/', '\\pm': '±', '\\mp': '∓',
    '\\leq': '<=', '\\le': '<=', '\\geq': '>=', '\\ge': '>=', '\\neq': '≠', '\\ne': '≠',
    '\\approx': '≈', '\\infty': '∞', '\\pi': 'пи', '\\alpha': 'альфа', '\\beta': 'бета',
    '\\gamma': 'гамма', '\\theta': 'тета', '\\angle': 'угол', '\\triangle': 'треугольник',
    '\\sin': 'sin', '\\cos': 'cos', '\\tan': 'tg', '\\tg': 'tg', '\\cot': 'ctg', '\\ctg': 'ctg',
    '\\log': 'log', '\\ln': 'ln', '\\lg': 'lg', '\\sum': 'сумма', '\\int': 'интеграл',
    '\\to': '→', '\\rightarrow': '→', '\\Rightarrow': '⇒', '\\in': 'принадлежит',
    '\\cup': 'объединение', '\\cap': 'пересечение', '\\varnothing': 'пустое множество',
    '\\left': '', '\\right': '', '\\,': ' ', '\\;': ' ', '\\!': '', '\\quad': ' ', '\\qquad': ' ',
  };
  for (const [k, v] of Object.entries(cmd)) {
    s = s.split(k).join(` ${v} `);
  }

  // 6. Оставшиеся \command — снять обратный слэш, оставив слово
  s = s.replace(/\\([a-zA-Z]+)/g, '$1');

  // 7. Markdown-картинки/ссылки → выкинуть URL, оставить alt
  s = s.replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1');
  s = s.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1');

  // 8. Схлопнуть фигурные скобки и пробелы
  s = s.replace(/[{}]/g, ' ');
  s = s.replace(/\s+/g, ' ').trim();

  return s;
}
