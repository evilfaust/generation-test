/**
 * SQLite (а значит и оператор `~` PocketBase) приводит регистр только для
 * латиницы: `LIKE "%abc%"` найдёт «ABC», а `LIKE "%Треугольник%"` не найдёт
 * «треугольник». На боевой базе это видно невооружённым глазом — «треугольник»
 * находит 2801 задачу, «Треугольник» — 50.
 *
 * Обойти это можно только перебором регистров в самом фильтре. Достаточно трёх
 * написаний: как ввёл учитель, всё строчными и с заглавной первой буквы —
 * слова капсом в условиях задач не встречаются. Лишние варианты почти
 * бесплатны: с индексом на code выборка идёт по индексу до первой страницы.
 */
export function searchCaseVariants(query = '') {
  const q = String(query).trim();
  if (!q) return [];

  // Латиница и цифры и так ищутся без учёта регистра — перебор не нужен.
  if (!/[а-яё]/i.test(q)) return [q];

  const lower = q.toLocaleLowerCase('ru');
  const capitalized = lower.charAt(0).toLocaleUpperCase('ru') + lower.slice(1);
  return [...new Set([q, lower, capitalized])];
}

/** Минимальная длина запроса: по одной букве поиск бессмыслен и дорог. */
export const MIN_SEARCH_LENGTH = 2;
