// Чинит битые корни/аргументы в LaTeX, оставшиеся после плохого парсинга
// sdamgia (например при массовом импорте). Детерминированно, без сети —
// клиентский аналог части серверной cleanLatexFormula (pdf-service.js),
// но толерантный сразу ко всем трём форматам маркеров аргумента:
//   1. с обычными пробелами:   «начало аргумента: X конец аргумента»
//   2. с мягкими переносами:   «на­ча­ло ар­гу­мен­та: X конец ар­гу­мен­та»
//   3. слипшийся (без пробелов): «началоаргумента X конецаргумента»
//
// Типовой мусор в БД (см. скриншот пользователя):
//   \log_{\sqrt: начало аргумента: 3 конец аргумента}  →  \log_{\sqrt{3}}

// Маркер аргумента «начало … X … конец» → {X}. «начало» с \s* покрывает и
// слипшийся, и пробельный вариант; конец — аналогично. Нежадный [\s\S]*?
// + цикл снаружи корректно разворачивают вложенные маркеры изнутри наружу.
// «начало» и «аргумента» — два слова в пробельном варианте, одно в слипшемся:
// \s* между ними покрывает оба (мягкие переносы уже сняты на шаге 1).
const ARG_MARKER =
  /начало\s*аргумента\s*:?\s*([\s\S]*?)\s*конец\s*аргумента/i;

/**
 * Привести битые корни/аргументы из парсинга sdamgia к валидному LaTeX.
 * @param {string} text
 * @returns {string}
 */
export function fixLatexRoots(text) {
  if (!text || typeof text !== 'string') return text;
  let t = text;

  // 1. Невидимые символы: soft hyphen, zero-width space, nbsp.
  t = t.replace(/­/g, '').replace(/​/g, '').replace(/ /g, ' ');

  // 2. Unicode-корни → LaTeX (иногда sdamgia ставит символ вместо слова).
  t = t.replace(/√/g, '\\sqrt ').replace(/∛/g, '\\sqrt[3]').replace(/∜/g, '\\sqrt[4]');

  // 3. Маркеры аргумента «начало … конец» → {…}. Цикл — для вложенности.
  for (let i = 0; i < 30 && ARG_MARKER.test(t); i++) {
    t = t.replace(ARG_MARKER, (_, inner) => `{${inner.trim()}}`);
  }

  // 4. Словесные корни → \sqrt (после разворачивания аргументов, чтобы
  //    «корень из: {3}» превратилось в «\sqrt {3}»).
  t = t.replace(/корень\s*(\d+)\s*степени\s*из\s*:?/gi, (_, n) => `\\sqrt[${n}]`);
  t = t.replace(/корень\s*из\s*:?/gi, '\\sqrt');

  // 5. «\sqrt:» / «\sqrt[N]:» — срезаем двоеточие-артефакт.
  t = t.replace(/\\sqrt(\[\d+\])?\s*:/g, (_, deg) => `\\sqrt${deg || ''}`);

  // 6. Схлопываем пробел между \sqrt(или \sqrt[N]) и аргументом в {…}:
  //    «\sqrt {3}» → «\sqrt{3}».
  t = t.replace(/\\sqrt(\[\d+\])?\s+\{/g, (_, deg) => `\\sqrt${deg || ''}{`);

  return t;
}

/**
 * Есть ли в тексте признаки битых корней/аргументов (для подсветки кнопки).
 * @param {string} text
 * @returns {boolean}
 */
export function hasBrokenRoots(text) {
  if (!text || typeof text !== 'string') return false;
  const normalized = text.replace(/­/g, '').replace(/​/g, '');
  return /начало\s*аргумента|конец\s*аргумента|корень\s*из|корень\s*\d+\s*степени|\\sqrt\s*:|[√∛∜]/i.test(
    normalized
  );
}
